"""
Utilities for extracting reference answers from official answer-key PDFs.

Ground truth means the expected answer used as a reference when checking
answers generated by the solve-and-verify workflow. In this project,
the demo extracts official MCQ answers and passes the relevant expected
answer to the solve graph for verification.

This module also provides helpers for splitting descriptive questions
with OR alternatives and extracting answer text from a reference answer
branch. These helpers are available for evaluation workflows, but are
not currently called elsewhere in the repository.
"""
import re
from pathlib import Path
from pypdf import PdfReader


MCQ_ANSWER_RE = re.compile(
    r"Answer:\s*Correct Option:\s*\(([A-D])\)",
    re.IGNORECASE,
)


def load_pdf_text(path: str | Path) -> str:
    """Extract and return text from all pages of a PDF."""
    reader = PdfReader(str(path))
    return "\n".join(page.extract_text() or "" for page in reader.pages)


def extract_mcq_answers(text: str) -> dict[str, str]:
    """Extract Section A MCQ answers as question-number-to-option mappings."""
    if "Section A" not in text or "Section B" not in text:
        raise ValueError("Could not find Section A and Section B in the answer key.")

    section_a = text.split("Section A", 1)[1].split("Section B", 1)[0]

    answers = [
        option.upper()
        for option in MCQ_ANSWER_RE.findall(section_a)
    ]

    if not answers:
        raise ValueError("No MCQ answer keys were found in Section A.")

    return {
        str(question_number): option
        for question_number, option in enumerate(answers, start=1)
    }
def split_or_branches(question_block: str) -> dict[str, str]:
    """Separate a descriptive question into its main and optional OR branches."""
    parts = re.split(r"(?m)^\s*OR\s*$", question_block, maxsplit=1)

    result = {
        "main": parts[0].strip(),
    }

    if len(parts) == 2:
        result["or"] = parts[1].strip()

    return result
def extract_answer_text(branch: str) -> str:
    """Extract answer text without including the next question."""
    match = re.search(
        r"(?ms)\bAnswer:\s*(.*?)(?="
        r"\n\s*(?:Why\?|"
        r"\[Ch\s|"
        r"(?:Question\s*)?\d+\s*[.):]|"
        r"What\s+is\b)"
        r"|\Z)",
        branch,
    )

    if not match:
        raise ValueError("Could not find an Answer: block.")

    return " ".join(match.group(1).split())


def test_extract_answer_text_stops_before_next_question():
    """Do not include the next question in the extracted answer."""
    from evaluation.ground_truth import extract_answer_text

    branch = (
        "Question 21: Explain photosynthesis.\n"
        "Answer: Photosynthesis converts light energy into chemical energy.\n"
        "What is chlorophyll?"
    )

    result = extract_answer_text(branch)

    assert result == (
        "Photosynthesis converts light energy into chemical energy."
    )


def test_split_or_branches_separates_alternative():
    """Separate the main question from its OR alternative."""
    from evaluation.ground_truth import split_or_branches

    question = (
        "Question 21: Explain photosynthesis.\n"
        "OR\n"
        "Question 22: Explain respiration."
    )

    result = split_or_branches(question)

    assert result == {
        "main": "Question 21: Explain photosynthesis.",
        "or": "Question 22: Explain respiration.",
    }
